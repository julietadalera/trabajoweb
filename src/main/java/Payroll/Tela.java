    private void carregarTabela() {
    try {
        HttpClient client = HttpClient.newHttpClient();

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create("http://localhost:8080/items"))
                .GET()
                .build();

        HttpResponse<String> response = client.send(
                request,
                HttpResponse.BodyHandlers.ofString()
        );

        if (response.statusCode() == 200) {

            ObjectMapper mapper = new ObjectMapper();

            List<Item> itens = mapper.readValue(
                    response.body(),
                    new TypeReference<List<Item>>() {}
            );

            itensAtuais = itens;   // <-- ESTA es la línea nueva

            DefaultTableModel modelo =
                    (DefaultTableModel) tabelaItens.getModel();

            modelo.setRowCount(0);

            for (Item item : itens) {
                modelo.addRow(new Object[]{
                    item.getId(),
                    item.getNome(),
                    item.getTipo()
                });
            }

        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao buscar os itens. Código: "
                    + response.statusCode()
            );
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(
                this,
                "Erro: " + e
        );
    }
}

    private void mostrarImagem(String foto) {
        arquivoEscolhido = null; 
        jLabel10.setIcon(null);
        jLabel10.setText("");

        if (foto == null || foto.isBlank()) {
            jLabel10.setText("Sem imagem");
            return;
        }

        try {
            java.net.URL url = URI.create("http://localhost:8080/img/" + foto).toURL();
            javax.swing.ImageIcon icon = new javax.swing.ImageIcon(url);

            if (icon.getIconWidth() <= 0) {
                jLabel10.setText("Imagem não encontrada");
                return;
            }

            java.awt.Image img = icon.getImage()
                    .getScaledInstance(200, -1, java.awt.Image.SCALE_SMOOTH);
            jLabel10.setIcon(new javax.swing.ImageIcon(img));

        } catch (Exception e) {
            jLabel10.setText("Imagem não encontrada");
        }
    }

