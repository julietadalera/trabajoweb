    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        try {
        int linha = tabelaItens.getSelectedRow();

      
        if (linha == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um item na tabela para editar."
            );
            return;
        }

        Long id = Long.valueOf(
                tabelaItens.getValueAt(linha, 0).toString()
        );

        String nome = txtNome.getText().trim();
        String tipo = cmbTipo.getSelectedItem().toString();

        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite um nome.");
            return;
        }

        String json = montarJson(nome, tipo);

        HttpClient client = HttpClient.newHttpClient();

      
        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create("http://localhost:8080/items/" + id))
                .header("Content-Type", "application/json")
                .PUT(HttpRequest.BodyPublishers.ofString(json))
                .build();

        HttpResponse<String> response = client.send(
                request,
                HttpResponse.BodyHandlers.ofString()
        );

        if (response.statusCode() == 200) {

            JOptionPane.showMessageDialog(
                    this,
                    "Item atualizado com sucesso!"
            );

            txtNome.setText("");
            cmbTipo.setSelectedIndex(0);
            limparImagem();
            carregarTabela();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao editar. Código: "
                    + response.statusCode()
            );
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
                this,
                "Erro: " + e.getMessage()
        );
    }
}
