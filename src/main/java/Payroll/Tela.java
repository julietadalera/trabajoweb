    private String enviarImagem(java.io.File arquivo) throws Exception {
        String nomeArquivo = arquivo.getName().toLowerCase();
        String extensao = nomeArquivo.substring(nomeArquivo.lastIndexOf('.') + 1);
        String boundary = "----JavaBoundary" + System.currentTimeMillis();

        String tipoConteudo = java.nio.file.Files.probeContentType(arquivo.toPath());
        if (tipoConteudo == null) {
            tipoConteudo = "application/octet-stream";
        }

        java.io.ByteArrayOutputStream corpo = new java.io.ByteArrayOutputStream();
        corpo.write(("--" + boundary + "\r\n"
                + "Content-Disposition: form-data; name=\"file\"; filename=\"imagem." + extensao + "\"\r\n"
                + "Content-Type: " + tipoConteudo + "\r\n\r\n")
                .getBytes(java.nio.charset.StandardCharsets.UTF_8));
        corpo.write(java.nio.file.Files.readAllBytes(arquivo.toPath()));
        corpo.write(("\r\n--" + boundary + "--\r\n")
                .getBytes(java.nio.charset.StandardCharsets.UTF_8));

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create("http://localhost:8080/upload"))
                .header("Content-Type", "multipart/form-data; boundary=" + boundary)
                .POST(HttpRequest.BodyPublishers.ofByteArray(corpo.toByteArray()))
                .build();

        HttpResponse<String> response = HttpClient.newHttpClient().send(
                request,
                HttpResponse.BodyHandlers.ofString()
        );

        if (response.statusCode() != 200 && response.statusCode() != 201) {
            throw new Exception("Erro ao enviar a imagem. Código: " + response.statusCode());
        }

        return response.body().trim();
    }

    private String montarJson(String nome, String tipo) throws Exception {
        java.util.Map<String, String> dados = new java.util.HashMap<>();
        dados.put("nome", nome);
        dados.put("tipo", tipo);

        if (arquivoEscolhido != null) {
            dados.put("foto", enviarImagem(arquivoEscolhido));
        }

        return new ObjectMapper().writeValueAsString(dados);
    }

